"""Fill typical_metrics in every blocks/<id>/block.yaml from Checker runs.

Each block is simulated at its default params, once per value of its choice
params (e.g. D_clip, Q_model), at the standard test signal (TargetSpec
default). Only the typical_metrics section of block.yaml is rewritten; comments
elsewhere are kept. Rerun after changing models/ (values come from the models used).

Usage: python -m scripts.fill_typical_metrics [block_id ...]
"""
import itertools
import re
import sys

from pedal_agent.build import BLOCKS_DIR, load_block
from pedal_agent.checker import MODELS, check
from pedal_agent.schemas import BlockInstance, Candidate, TargetSpec

SECTION_RE = re.compile(r"^typical_metrics:.*\n(?:[ \t]+.*\n)*", re.M)  # header + indented lines


def variants(meta: dict) -> list[dict]:
    choices = {k: p["choices"] for k, p in meta["params"].items() if p["type"] == "choice"}
    return [dict(zip(choices, combo)) for combo in itertools.product(*choices.values())]


def measure(block_id: str) -> dict[str, dict]:
    _, meta = load_block(block_id)
    spec = TargetSpec(goal_text="typical_metrics", targets=[])
    out = {}
    for overrides in variants(meta):
        key = ",".join(f"{k}={v}" for k, v in overrides.items()) or "default"
        rep = check(Candidate(chain=[BlockInstance(block_id=block_id, params=overrides)], rationale=""), spec)
        if rep.errors:
            raise RuntimeError(f"{block_id} {key}: {rep.errors}")
        out[key] = {k: float(f"{v:.3g}") for k, v in rep.metrics.items()}
    return out


def section(metrics: dict[str, dict], amp_v: float, f0_hz: float, models: str) -> str:
    lines = [f"typical_metrics:   # generated by scripts/fill_typical_metrics.py: defaults, "
             f"{f0_hz:g} Hz {amp_v * 1e3:g} mV EMF, models {models}"]
    for key, m in metrics.items():
        lines.append(f"  {key}: {{" + ", ".join(f"{k}: {v:g}" for k, v in m.items()) + "}")
    return "\n".join(lines) + "\n"


def main(ids: list[str]) -> int:
    signal = TargetSpec(goal_text="", targets=[]).test_signal
    for block_id in ids or sorted(p.name for p in BLOCKS_DIR.iterdir() if p.is_dir()):
        path = BLOCKS_DIR / block_id / "block.yaml"
        text = path.read_text(encoding="utf-8")
        if not SECTION_RE.search(text):
            raise RuntimeError(f"{path}: no typical_metrics section")
        metrics = measure(block_id)
        new = SECTION_RE.sub(lambda _: section(metrics, signal["amp_v"], signal["f0_hz"],
                                               MODELS.replace("\\", "/").split("/")[-1]), text, count=1)
        path.write_text(new, encoding="utf-8")
        print(f"{block_id}:")
        for key, m in metrics.items():
            print(f"  {key:22s} {m}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
